import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { loadCorpus, loadQuestions, validateDataset } from './dataset.js'
import { CHUNKERS, RETRIEVERS, runGeneration, runRetrieval, type GenerationConfig, type RetrievalResults } from './experiments.js'
import { BASELINE, generationSection, retrievalSection } from './report.js'
import { specName } from './chunking.js'

function flag(name: string): string | undefined {
  const i = process.argv.indexOf(`--${name}`)
  return i >= 0 ? process.argv[i + 1] : undefined
}

async function readJson<T>(path: string): Promise<T> {
  return JSON.parse(await readFile(path, 'utf8')) as T
}

async function main() {
  const [cmd] = process.argv.slice(2)
  const docs = await loadCorpus()
  const questions = await loadQuestions()

  if (cmd === 'validate') {
    const r = validateDataset(questions, docs)
    console.log(`${docs.length} documents, ${r.answerable} answerable + ${r.unanswerable} unanswerable questions`)
    console.log('style:', r.byStyle)
    console.log('gold spans per document:', r.perDoc)
    if (r.errors.length) {
      console.error(`\n${r.errors.length} problem(s):\n- ${r.errors.join('\n- ')}`)
      process.exit(1)
    }
    console.log('dataset OK')
    return
  }

  const invalid = validateDataset(questions, docs).errors
  if (invalid.length) throw new Error(`dataset is invalid, run "npm run validate":\n- ${invalid.join('\n- ')}`)
  await mkdir('results', { recursive: true })

  if (cmd === 'retrieval') {
    const chunkerFilter = flag('chunkers')?.split(',')
    const retrieverFilter = flag('retrievers')?.split(',')
    const res = await runRetrieval(
      docs,
      questions,
      CHUNKERS.filter((c) => !chunkerFilter || chunkerFilter.includes(specName(c))),
      RETRIEVERS.filter((r) => !retrieverFilter || retrieverFilter.includes(r.key)),
      (m) => console.log(m),
    )
    await writeFile('results/retrieval.json', JSON.stringify(res, null, 2) + '\n')
    console.log('wrote results/retrieval.json')
    return
  }

  if (cmd === 'generation') {
    const model = flag('model') ?? 'qwen2.5:3b'
    const retrieval = await readJson<RetrievalResults>('results/retrieval.json')
    const best = [...retrieval.runs].sort((a, b) => b.metrics.mrr - a.metrics.mrr)[0]!
    const bestChunker = CHUNKERS.find((c) => specName(c) === best.chunker)!
    const baseChunker = CHUNKERS.find((c) => specName(c) === BASELINE.chunker)!
    const configs: GenerationConfig[] = [
      { label: 'closed-book (no retrieval)', condition: 'closed-book' },
      { label: 'RAG — IADocuments today (k=5)', condition: 'rag', chunker: baseChunker, retriever: BASELINE.retriever, k: 5 },
      { label: `RAG — best retrieval: ${best.chunker} / ${best.retriever} (k=5)`, condition: 'rag', chunker: bestChunker, retriever: best.retriever, k: 5 },
      { label: 'oracle (gold paragraph as context)', condition: 'oracle' },
    ]
    const res = await runGeneration(docs, questions, configs, model, (m) => console.log(m))
    await writeFile('results/generation.json', JSON.stringify(res, null, 2) + '\n')
    console.log('wrote results/generation.json')
    return
  }

  if (cmd === 'report') {
    const parts = ['# Results\n', 'Generated by `npm run report` from `results/*.json`.\n']
    parts.push(retrievalSection(await readJson('results/retrieval.json'), questions))
    try {
      parts.push('\n' + generationSection(await readJson('results/generation.json'), questions))
    } catch {
      parts.push('\n_(no generation results yet — run `npm run generation`)_')
    }
    await writeFile('results/report.md', parts.join('\n') + '\n')
    console.log('wrote results/report.md')
    return
  }

  console.error('usage: cli.ts validate | retrieval [--chunkers a,b] [--retrievers a,b] | generation [--model m] | report')
  process.exit(1)
}

main().catch((e) => {
  console.error(e instanceof Error ? e.message : e)
  process.exit(1)
})
